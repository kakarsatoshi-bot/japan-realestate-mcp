export function lookupPrefecture(name: string): PrefectureInfo | null {
  const normalized = name.trim();
  return PREFECTURES.find((p) =>
    p.name === normalized ||
    p.name === normalized + "都" ||
    p.name === normalized + "道" ||
    p.name === normalized + "府" ||
    p.name === normalized + "県"
  ) ?? null;
}

export function lookupCity(prefectureCode: string, cityName: string): CityInfo | null {
  const normalized = cityName.trim();
  return CITIES.find((c) =>
    c.prefectureCode === prefectureCode && c.name === normalized
  ) ?? null;
}

export function getCitiesByPrefecture(prefectureCode: string): CityInfo[] {
  return CITIES.filter((c) => c.prefectureCode === prefectureCode);
}

export function lookupPropertyType(typeName: string): string | null {
  return PROPERTY_TYPE_MAP[typeName.trim()] ?? null;
}
